-- 目标库：dd-vue（MySQL 8.0.46，库默认 utf8mb4 / utf8mb4_0900_ai_ci）
--
-- 执行前请确认：
--   1. 已在目标库上执行（USE `dd-vue`;），本脚本不切库，避免误伤其他库；
--   2. 本脚本未包含 DROP TABLE，重复执行会因表已存在而报错，这是有意的保护；
--   3. 本表只存角色 ID / 部门 ID，不建外键，按顺序先执行 02_sys_role.sql、03_sys_dept.sql。
-- =============================================================================

CREATE TABLE IF NOT EXISTS `sys_role_dept`
(
    `role_id` bigint NOT NULL COMMENT '角色ID',
    `dept_id` bigint NOT NULL COMMENT '部门ID',
    -- 联合主键：同一个角色对同一个部门只允许一行，重复配置由数据库直接拒绝
    PRIMARY KEY (`role_id`, `dept_id`),
    -- 反向查询：某个部门被哪些角色引用（调整/删除部门前检查）
    KEY `idx_sys_role_dept_dept_id` (`dept_id`)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_0900_ai_ci COMMENT ='角色与部门关联表（自定义数据权限）';

