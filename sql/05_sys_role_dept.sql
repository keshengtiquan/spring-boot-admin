-- 说明（不执行，仅备忘）
--
-- 1) 这张表什么时候才有意义
--    只在 sys_role.data_scope = '2'（自定义数据权限）时使用：
--      - 1 全部数据权限   ：不看本表
--      - 2 自定义数据权限 ：看本表，角色可见 dept_id 并集内的数据
--      - 3 本部门数据权限 ：按用户自己的 sys_user.dept_id
--      - 4 本部门及以下   ：按 sys_dept.ancestors 展开
--      - 5 仅本人数据权限 ：只看自己创建的数据
--    RoleServiceImpl#createRole 会校验一致性：data_scope = 2 时 deptIds 必填且非空，
--    其他数据范围不允许传 deptIds。这样不会出现"范围是全部、却残留一批部门记录"的脏数据。
--
-- 2) 为什么用 (role_id, dept_id) 联合主键
--    与 sys_user_role 同理：纯关联表没有独立生命周期，联合主键天然防重复，
--    物理删除即取消授权，也省掉一个额外的唯一索引。
--
-- 3) 为什么给 dept_id 单独建索引
--    联合主键最左前缀是 role_id，支撑"角色 → 部门"（登录后组装数据权限必走）；
--    反过来"部门 → 角色"（改/删部门前检查哪些角色引用了它）用不上前缀，所以补一个。
--
-- 4) 为什么没有审计字段
--    关联关系属于角色配置的一部分，审计看 sys_role；如果需要记录"谁在什么时候改了数据权限"，
--    属于操作日志，单独记，不要往关联表塞审计列。
--
-- 5) 为什么不加物理外键
--    与 sys_user_role 一致，引用完整性放应用层：创建时校验部门存在，
--    删除角色/部门前先清理本表关联行（当前只实现了创建，后续删除接口要补）。
--
-- 6) 安全默认值
--    如果某个角色 data_scope = 2 但本表没有记录，解析出的可见范围是"空"，
--    而不是"全部"——权限判断宁可少给数据，也不要因为漏配而放开全量数据。
--
-- 7) 命名与初始化
--    表名沿用 sys_role_dept 的"角色在前、部门在后"顺序，与联合主键顺序一致。
--    本脚本不预置数据；需要时手工执行，例如：
--
--    INSERT INTO `sys_role_dept` (`role_id`, `dept_id`) VALUES (2, 100), (2, 101);
