-- 执行前请确认：
--   1. 已在目标库上执行（USE `dd-vue`;），本脚本不切库，避免误伤其他库；
--   2. 本脚本未包含 DROP TABLE，重复执行会因表已存在而报错，这是有意的保护；
--   3. 本表只存用户 ID / 角色 ID，不建外键，按顺序先执行 01_sys_user.sql、02_sys_role.sql。
-- =============================================================================

CREATE TABLE IF NOT EXISTS `sys_user_role`
(
    `user_id` bigint NOT NULL COMMENT '用户ID',
    `role_id` bigint NOT NULL COMMENT '角色ID',
    -- 联合主键：同一个用户对同一个角色只允许一行，重复授权由数据库直接拒绝
    PRIMARY KEY (`user_id`, `role_id`),
    -- 反向查询：某个角色下有哪些用户
    KEY `idx_sys_user_role_role_id` (`role_id`)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_0900_ai_ci COMMENT ='用户与角色关联表';

-- -----------------------------------------------------------------------------
-- 说明（不执行，仅备忘）
--
-- 1) 为什么用 (user_id, role_id) 联合主键，而不是自增 id
--    这是纯关联表，没有独立生命周期：一行记录的全部意义就是"用户 X 拥有角色 Y"。
--    联合主键天然保证不重复授权，物理删除就是解除授权，也省掉一个额外的唯一索引。
--    如果加自增 id，还得再建 (user_id, role_id) 唯一索引，索引维护成本反而更高。
--
-- 2) 为什么还要给 role_id 单独建索引
--    联合主键的最左前缀是 user_id，能支撑"用户 → 角色"的查询（登录后取权限必走）；
--    反过来"角色 → 用户"（查看某角色下的用户、删除角色前检查引用）用不上这个前缀，
--    所以补一个 role_id 索引。
--
-- 3) 为什么没有 create_by / create_time 之类审计字段
--    关联关系本身就是用户/角色的一部分，审计看 sys_user / sys_role 即可；
--    如果业务需要"谁在什么时候给谁授了权"，那属于操作日志，应该单独记，
--    不要往关联表里塞审计列，否则每次授权/解除都是一次全量更新。
--
-- 4) 为什么不加物理外键
--    与 sys_user / sys_role / sys_dept 保持一致：引用完整性放应用层。
--    外键会让删用户、删角色、数据迁移、分库分表都变麻烦，且失败信息对上层不友好。
--    应用层的约束是：
--      - 创建用户时先校验 role_id 都存在（UserServiceImpl#validateRolesExist）；
--      - 删除用户/角色时先删本表的关联行（当前只实现了创建，后续删除接口要补）。
--
-- 5) 命名与初始化
--    表名沿用 sys_user_role 的"用户在前、角色在后"顺序，与联合主键顺序一致，
--    避免同一个关系出现两种写法。本脚本不预置数据。
-- -----------------------------------------------------------------------------
