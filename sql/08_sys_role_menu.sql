--
-- 执行前请确认：
--   1. 已在目标库上执行（USE `dd-vue`;），本脚本不切库，避免误伤其他库；
--   2. 本脚本未包含 DROP TABLE，重复执行会因表已存在而报错，这是有意的保护；
--   3. 本表只存角色 ID / 菜单 ID，不建外键，按顺序先执行 02_sys_role.sql、06_sys_menu.sql。
-- =============================================================================

CREATE TABLE IF NOT EXISTS `sys_role_menu`
(
    `role_id` bigint NOT NULL COMMENT '角色ID',
    `menu_id` bigint NOT NULL COMMENT '菜单ID',
    -- 联合主键：同一个角色对同一个菜单只允许一行，重复授权由数据库直接拒绝
    PRIMARY KEY (`role_id`, `menu_id`),
    -- 反向查询：某个菜单被哪些角色引用（调整/删除菜单前检查）
    KEY `idx_sys_role_menu_menu_id` (`menu_id`)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_0900_ai_ci COMMENT ='角色与菜单关联表';

-- -----------------------------------------------------------------------------
-- 说明（不执行，仅备忘）
--
-- 1) 多对多语义
--    一个角色可以拥有多个菜单，一个菜单也可以被多个角色拥有。
--    这里存的是"角色被授予了哪些菜单"，包含目录（M）、菜单（C）和按钮（F）：
--      - 目录/菜单决定前端侧边栏与路由；
--      - 按钮决定后端 @SaCheckPermission("system:user:add") 这类按钮级权限。
--    所以分配菜单时，前端菜单树的勾选结果（含半选的父节点）应整体传过来。
--
-- 2) 为什么用 (role_id, menu_id) 联合主键
--    与 sys_user_role / sys_role_dept 同理：纯关联表没有独立生命周期，
--    联合主键天然防重复授权，物理删除即取消授权，也省掉一个额外的唯一索引。
--
-- 3) 为什么给 menu_id 单独建索引
--    联合主键最左前缀是 role_id，支撑"角色 → 菜单"（登录后取权限必走）；
--    反过来"菜单 → 角色"（删除/移动菜单前检查引用）用不上前缀，所以补一个。
--
-- 4) 为什么没有审计字段
--    授权关系属于角色配置的一部分，审计看 sys_role；"谁在什么时候改了菜单授权"
--    属于操作日志，单独记，不要往关联表塞审计列。
--
-- 5) 为什么不加物理外键
--    与其它关联表一致，引用完整性放应用层：
--      - 分配时校验角色、菜单都存在（RoleServiceImpl#validateMenusExist）；
--      - 删除角色/菜单前先清理本表关联（当前只实现了分配，删除接口后续补）。
--
-- 6) 分配语义：全量覆盖
--    分配接口（PUT /system/role/{roleId}/menus）是"覆盖式"：
--    一个事务里先 DELETE 该角色的旧关联，再批量 INSERT 新关联；
--    传空数组表示清空该角色的所有菜单权限。不要做成"增量追加"，
--    否则前端取消勾选的菜单永远不会被撤销。
--
-- 7) 授权示例（可选，按需执行）
--    给 2002 角色分配"系统管理"目录及下面四个菜单：
--
--    INSERT INTO `sys_role_menu` (`role_id`, `menu_id`)
--    VALUES (2002, 2000), (2002, 2001), (2002, 2002), (2002, 2003), (2002, 2004);
--
-- 8) 与数据权限（sys_role_dept）无关
--    本表控制"能看到哪些菜单/能点哪些按钮"；
--    sys_role_dept 控制"能看到哪些部门的数据"（data_scope = 2 时）。
--    两者不要混在一起。
